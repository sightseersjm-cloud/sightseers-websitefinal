/** Most catalog durations are times ("3 to 5 hours", "Evening"); some hold a format instead ("Boat & snorkel", "Private charter, up to 8"). */
const isTime = v => /(\d|^\s*(evening|morning|afternoon|night|half|full|all day))/i.test(String(v || '')) && !/up to|charter/i.test(String(v || ''));

/** The price as the catalog card shows it: "$80" + "per person" / "per group (up to N)", or on request. */
function priceInfo(t) {
  const v = Number(t.priceValue || 0);
  if (!(v > 0)) return { has: false, value: 0, main: 'Price on request', unit: '', line: 'Price on request' };
  const grp = /per group/i.test(String(t.priceLabel || '') + (t.per === 'group' ? ' per group' : ''));
  const unit = grp ? 'per group' + (t.cap ? ' (up to ' + t.cap + ')' : '') : 'per person';
  const main = '$' + v.toLocaleString('en-US');
  return { has: true, value: v, main, unit, line: 'From ' + main + ' ' + unit };
}

/** Meta description: the experience's own description plus its "from" price, kept to about 160 characters with the price intact.
 *  Whole sentences are kept where possible so the snippet does not stop mid-thought. */
function metaDescription(t, price) {
  const tail = price.has ? price.line + '.' : 'Price on request.';
  const text = String(t.desc || t.hero || '').replace(/\s+/g, ' ').trim();
  const MAX = 160;
  if ((text + ' ' + tail).length <= MAX) return text + ' ' + tail;
  let out = '';
  for (const s of text.match(/[^.!?]+[.!?]+(?=\s|$)/g) || []) {
    const next = (out ? out + ' ' : '') + s.trim();
    if ((next + ' ' + tail).length > MAX) break;
    out = next;
  }
  if (out) return out + ' ' + tail;
  let cut = text.slice(0, MAX - tail.length - 2);
  cut = cut.slice(0, Math.max(cut.lastIndexOf(' '), 40)).replace(/[\s,;:.\-]+$/, '');
  return cut + '\u2026 ' + tail;
}

function related(t, all) {
  return all.filter(o => o !== t && o.country === t.country)
    .map(o => ({ o, score: (o.area && o.area === t.area ? 2 : 0) + (o.type === t.type ? 1 : 0) }))
    .sort((a, b) => b.score - a.score || a.o.title.localeCompare(b.o.title))
    .slice(0, 4).map(x => x.o);
}

function structuredData(t, ctx) {
  const price = priceInfo(t);
  const trip = {
    '@context': 'https://schema.org', '@type': 'TouristTrip',
    name: t.title, description: String(t.desc || '').trim(), url: ctx.url, image: abs(t.image),
    provider: { '@type': 'TravelAgency', name: BRAND + ' Adventures', url: SITE }
  };
  if (t.best) trip.touristType = String(t.best).split(' · ').join(', ');
  if (price.has) trip.offers = { '@type': 'Offer', price: String(price.value), priceCurrency: 'USD', url: ctx.url };
  const crumbs = {
    '@context': 'https://schema.org', '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Home', item: SITE + '/' },
      { '@type': 'ListItem', position: 2, name: 'Tours', item: SITE + '/tours' },
      { '@type': 'ListItem', position: 3, name: t.title, item: ctx.url }
    ]
  };
  return `<script type="application/ld+json">${json(trip)}</script>\n<script type="application/ld+json">${json(crumbs)}</script>`;
}

