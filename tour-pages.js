/**
 * tour-pages.js
 * One static, crawlable page per water and land experience in the All Experiences catalog, at /tours/<slug>.
 *
 * Why static pages rather than copies of the app: the app is a 3 MB document, so a copy per experience would add
 * about 380 MB to every deploy. These pages are about 15 KB each, carry the real content in the HTML (what search
 * engines read first), load fast on a phone, and send visitors into the existing enquiry flow:
 *
 *   Request button  ->  /booking?experience=<slug>  (opens the same enquiry as the catalog's "Inquire now")
 *   WhatsApp / call ->  the planners' numbers
 *   funnel events   ->  /api/track  (tour_page, book_cta, quote_cta, keyed exp-<slug>)
 *
 * Everything shown comes from the CURATED_TOURS entry (title, tagline, description, highlights, area, duration,
 * "from" price), so the page and the catalog card can never disagree about a price. Nothing is invented: there are no
 * ratings, reviews or availability claims. The slug comes from ssTourSlug() in Design_Reference.html (build.js
 * evaluates that function), the same one the catalog uses for its links.
 *
 * Also keeps a generated block of <url> entries in public/sitemap.xml, between ss-tour-urls markers.
 */
