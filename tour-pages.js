function isOurs(file) {
  const fd = fs.openSync(file, 'r');
  try { const b = Buffer.alloc(300); const n = fs.readSync(fd, b, 0, 300, 0); return b.toString('utf8', 0, n).includes(MARKER); }
  finally { fs.closeSync(fd); }
}

/** Experiences that get a page: the same set the catalog lists (water and land). Validates slugs before anything is written. */
function planTourPages(curated, slugOf) {
  const list = curated.filter(t => t.type === 'water' || t.type === 'land');
  if (!list.length) throw new Error('Tour pages: CURATED_TOURS has no water or land experiences');
  const seen = new Map();
  for (const t of list) {
    const slug = slugOf(t);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) || slug.length > 90) throw new Error(`Tour pages: "${t.title}" produces an unusable slug ${JSON.stringify(slug)}`);
    if (seen.has(slug)) throw new Error(`Tour pages: "${seen.get(slug)}" and "${t.title}" both produce /tours/${slug}. Give one a slug field.`);
    seen.set(slug, t.title);
    for (const f of ['title', 'desc', 'image', 'country']) if (!t[f]) throw new Error(`Tour pages: "${t.title}" has no ${f}`);
  }
  return list;
}

function updateSitemap(file, urls, today) {
  let xml = fs.readFileSync(file, 'utf8');
  const had = new Map();
  const block = new RegExp('[ \\t]*' + SM_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + SM_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[ \\t]*\\n?');
  const m = block.exec(xml);
  if (m) {
    for (const u of m[0].matchAll(/<loc>([^<]+)<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g)) had.set(u[1], u[2]);   // keep a URL's lastmod until it changes
    xml = xml.replace(block, '');
  } else if (xml.includes('ss-tour-urls')) throw new Error('sitemap.xml has an unmatched ss-tour-urls marker');
  if (!xml.includes('</urlset>')) throw new Error('sitemap.xml has no </urlset>');
  const entries = urls.map(loc =>
    `  <url>\n    <loc>${loc}</loc>\n    <lastmod>${had.get(loc) || today}</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>0.7</priority>\n  </url>`).join('\n');
  xml = xml.replace('</urlset>', `  ${SM_START}\n${entries}\n  ${SM_END}\n</urlset>`);
  fs.writeFileSync(file, xml, 'utf8');
}

/* The pages themselves are made on request by /api/tour-page, so an edit made in the admin shows without a new deploy.
   This step only checks that every slug is usable, removes pages an earlier build wrote (a file on disk would win over the
   rewrite), and keeps the sitemap list. */
function writeTourPages({ curated, slugOf, publicDir, today }) {
  const list = planTourPages(curated, slugOf);
  const toursDir = path.join(publicDir, 'tours');
  const urls = list.map(t => SITE + '/tours/' + slugOf(t));
  let removed = 0;
  if (fs.existsSync(toursDir)) {
    for (const ent of fs.readdirSync(toursDir, { withFileTypes: true })) {
      if (!ent.isDirectory()) continue;
      const file = path.join(toursDir, ent.name, 'index.html');
      if (fs.existsSync(file) && isOurs(file)) {
        fs.unlinkSync(file);
        if (!fs.readdirSync(path.join(toursDir, ent.name)).length) fs.rmdirSync(path.join(toursDir, ent.name));
        removed++;
      }
    }
  }
  updateSitemap(path.join(publicDir, 'sitemap.xml'), urls, today);
  return { written: list.length, removed };
}

