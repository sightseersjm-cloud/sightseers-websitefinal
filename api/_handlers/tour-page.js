/* One experience page, made when asked for: /tours/<slug> is rewritten here (see vercel.json). It uses the experience list from
   the site's code with the owner's edits laid over it, so a change made in the admin shows within a few minutes without a deploy.
   If the storage cannot be read the page is made from the list in the code. */
const { readSettings } = require('../_lib/siteStore');
const catalog = require('../_lib/catalog');
const tourPages = require('../../tour-pages');

let BASE = [];
try { BASE = require('../_data/curated-tours.json'); } catch (e) { /* generated by build.js */ }

const SITE = 'https://www.sightseerscaribbean.com';

function notFound(res) {
  res.setHeader('Content-Type', 'text/html; charset=utf-8');
  res.setHeader('Cache-Control', 'public, s-maxage=60, stale-while-revalidate=300');
  return res.status(404).send('<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex"><title>Experience not found | Sight Seers Caribbean</title></head>'
    + '<body style="font-family:Raleway,Arial,sans-serif;max-width:560px;margin:12vh auto;padding:0 22px;color:#15293d"><h1 style="font-family:Georgia,serif;color:#063a63">We could not find that experience</h1>'
    + '<p>It may have been renamed or taken off the website.</p><p><a href="/tours" style="color:#063a63;font-weight:700">Browse all experiences</a></p></body></html>');
}

module.exports = async function handler(req, res) {
  if (req.method !== 'GET' && req.method !== 'HEAD') return res.status(405).end();
  const slug = String((req.query && req.query.slug) || '').toLowerCase();
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) || slug.length > 90) return notFound(res);
  let doc = null;
  try { const s = await readSettings({ cached: true }); doc = s && s.ss_catalog_v1 && s.ss_catalog_v1.experiences; } catch (e) { doc = null; }
  const list = catalog.effective('experiences', BASE, doc).filter(t => (t.type === 'water' || t.type === 'land') && t.title && t.desc && t.image && t.country);
  const t = list.find(x => catalog.slugOf(x) === slug);
  if (!t) return notFound(res);
  const html = tourPages.renderPage(t, { url: SITE + '/tours/' + slug, slug, all: list, slugOf: catalog.slugOf });
  res.setHeader('Content-Type', 'text/html; charset=utf-8');
  res.setHeader('Cache-Control', 'public, s-maxage=300, stale-while-revalidate=3600');
  return res.status(200).send(html);
};
